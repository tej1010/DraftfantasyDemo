export function buildStaticWaiverClaim(
  drop: Player,
  add: Player,
  leagueId: string,
  teamName = 'Tejpal FC',
  priority = 2
): WaiverClaim {
  return {
    id: `claim-${Date.now()}`,
    leagueId,
    teamId: 'team-user',
    teamName,
    playerToDropId: drop.id,
    playerToDropName: drop.name,
    playerToAddId: add.id,
    playerToAddName: add.name,
    status: 'Pending',
    priorityValue: priority,
    timestamp: new Date().toISOString(),
  };
}
